package be.ecampus.ecampusbackend.model;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import java.time.Instant;
import java.util.UUID;

/**
 * A person of the application. Admins and superadmins are users with a higher
 * {@link Role}: one person is one row and one login.
 */
@Entity
@Table(name = "users")
public class User {

    // Generated by Hibernate before the insert, so the object has its id as
    // soon as it is saved. The database default (gen_random_uuid) is not used.
    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    private UUID id;

    @Column(name = "firstname", nullable = false, length = 100)
    private String firstname;

    @Column(name = "lastname", nullable = false, length = 100)
    private String lastname;

    @Column(name = "mail", nullable = false, length = 255)
    private String mail;

    // Hash computed by Spring Security, never the password itself. It must
    // never be returned by the API nor written to logs.
    @Column(name = "password_hash", nullable = false, length = 255)
    private String passwordHash;

    @Column(name = "two_factor_enabled", nullable = false)
    private boolean twoFactorEnabled = false;

    @Column(name = "two_factor_secret")
    private String twoFactorSecret;

    // STRING stores the name ("ACTIF"), not its position: reordering the enum
    // must never change the meaning of rows already in the database.
    @Enumerated(EnumType.STRING)
    @Column(name = "status", nullable = false, length = 20)
    private UserStatus status = UserStatus.ACTIF;

    @Enumerated(EnumType.STRING)
    @Column(name = "role", nullable = false, length = 20)
    private Role role = Role.USER;

    // Plain id for now; it becomes a relation to User once we handle links.
    @Column(name = "created_by_id")
    private UUID createdById;

    // Set when the object is created and never rewritten by an UPDATE.
    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt = Instant.now();

    protected User() {
    }

    /**
     * Creates a regular, active user without two-factor authentication.
     *
     * @param firstname    first name
     * @param lastname     last name
     * @param mail         e-mail address, unique ignoring case
     * @param passwordHash hash of the password, never the password itself
     */
    public User(String firstname, String lastname, String mail, String passwordHash) {
        this.firstname = firstname;
        this.lastname = lastname;
        this.mail = mail;
        this.passwordHash = passwordHash;
    }

    public UUID getId() {
        return id;
    }

    public String getFirstname() {
        return firstname;
    }

    public String getLastname() {
        return lastname;
    }

    public String getMail() {
        return mail;
    }

    public String getPasswordHash() {
        return passwordHash;
    }

    public boolean isTwoFactorEnabled() {
        return twoFactorEnabled;
    }

    public String getTwoFactorSecret() {
        return twoFactorSecret;
    }

    public UserStatus getStatus() {
        return status;
    }

    public Role getRole() {
        return role;
    }

    public UUID getCreatedById() {
        return createdById;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }
}